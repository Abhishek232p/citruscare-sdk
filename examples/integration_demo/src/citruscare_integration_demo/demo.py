"""Consumer-side integration demo using only CitrusCare's public API."""

from __future__ import annotations

import asyncio
import json
import os
from collections.abc import Iterator
from contextlib import contextmanager
from datetime import UTC, datetime
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from importlib.metadata import PackageNotFoundError, version
from threading import Thread
from typing import Any

from citruscare import (
    Agent,
    AssistantTurn,
    ConfigurationError,
    ConsentLedger,
    MemoryAuditSink,
    Message,
    OpenAICompatibleProvider,
    ProviderError,
    ScriptedProvider,
    Settings,
    StepLimitExceeded,
    Tool,
    ToolCall,
    ToolExecutionError,
    ToolRegistry,
)
from citruscare.clinical import ClinicalObservation

_LOCAL_COMPLETION = (
    "Fixed response from the local OpenAI-compatible protocol endpoint; "
    "this response was not generated by an AI model."
)


def _settings_from_environment() -> Settings:
    demo_environment = {
        "CITRUSCARE_API_KEY": "",
        "CITRUSCARE_MODEL": "citruscare-demo-model",
        "CITRUSCARE_BASE_URL": "https://example.invalid/v1",
        "CITRUSCARE_REQUEST_TIMEOUT": "5",
        "CITRUSCARE_MAX_TURNS": "4",
    }
    previous_values = {name: os.environ.get(name) for name in demo_environment}
    try:
        os.environ.update(demo_environment)
        return Settings.from_env()
    finally:
        for name, value in previous_values.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value


def _build_registry() -> ToolRegistry:
    async def lookup_reference(reference: str) -> dict[str, str]:
        await asyncio.sleep(0)
        if reference != "DEMO-REF-001":
            return {"reference": reference, "status": "not_found"}
        return {"reference": reference, "status": "active"}

    registry = ToolRegistry()
    registry.register(
        Tool(
            name="lookup_reference",
            description="Look up a synthetic demonstration reference.",
            parameters={
                "type": "object",
                "properties": {"reference": {"type": "string"}},
                "required": ["reference"],
                "additionalProperties": False,
            },
            handler=lookup_reference,
        )
    )
    registry.register(
        Tool(
            name="format_status",
            description="Format a status label synchronously.",
            parameters={
                "type": "object",
                "properties": {"status": {"type": "string"}},
                "required": ["status"],
                "additionalProperties": False,
            },
            handler=lambda status: f"Status: {status}",
        )
    )
    return registry


class _ProtocolEndpoint(BaseHTTPRequestHandler):
    """Local protocol fixture, not an LLM and not a simulated provider SDK."""

    def do_POST(self) -> None:
        if self.path == "/v1/failure/chat/completions":
            self.send_error(503)
            return
        if self.path != "/v1/chat/completions":
            self.send_error(404)
            return
        if self.headers.get("Authorization") != "Bearer demo-only-token":
            self.send_error(401)
            return
        try:
            request = json.loads(self.rfile.read(int(self.headers["Content-Length"])))
        except (KeyError, ValueError, json.JSONDecodeError):
            self.send_error(400)
            return
        if request.get("model") != "citruscare-demo-model":
            self.send_error(400)
            return
        body = json.dumps(
            {"choices": [{"message": {"content": _LOCAL_COMPLETION, "tool_calls": []}}]}
        ).encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def log_message(self, format: str, *args: Any) -> None:
        del format, args


@contextmanager
def _protocol_endpoint() -> Iterator[str]:
    server = ThreadingHTTPServer(("127.0.0.1", 0), _ProtocolEndpoint)
    thread = Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        host, port = server.server_address
        yield f"http://{host}:{port}/v1"
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=5)


async def _run_demo_async() -> dict[str, Any]:
    settings = _settings_from_environment()
    registry = _build_registry()
    audit = MemoryAuditSink()
    provider = ScriptedProvider(
        [
            AssistantTurn(
                tool_calls=(
                    ToolCall(
                        id="demo-call-1",
                        name="lookup_reference",
                        arguments={"reference": "DEMO-REF-001"},
                    ),
                )
            ),
            AssistantTurn(content="Reference DEMO-REF-001 is active."),
        ]
    )
    agent_result = await Agent(
        provider,
        registry,
        instructions="Use the registered tools to answer the synthetic example.",
        max_turns=settings.max_turns,
        audit_sink=audit,
    ).run("Check synthetic reference DEMO-REF-001.")
    tool_message = next(
        message for message in agent_result.messages if message.role == "tool"
    )

    formatted_status = await registry.invoke(
        ToolCall(
            id="demo-call-2",
            name="format_status",
            arguments={"status": "active"},
        )
    )

    consent = ConsentLedger()
    grant = consent.grant("synthetic-subject-001", "demo-purpose")
    consent_active_after_grant = consent.has_consent(
        "synthetic-subject-001", "demo-purpose"
    )
    revoked = consent.revoke("synthetic-subject-001", "demo-purpose")

    observation = ClinicalObservation(
        code="demo-heart-rate",
        value=72,
        unit="beats/min",
        effective_at=datetime(2026, 1, 1, tzinfo=UTC),
        subject_reference="Patient/synthetic-subject-001",
    )

    provider_http_error = ""
    with _protocol_endpoint() as base_url:
        http_provider = OpenAICompatibleProvider(
            Settings(
                api_key="demo-only-token",
                model=settings.model,
                base_url=base_url,
                request_timeout=settings.request_timeout,
                max_turns=settings.max_turns,
            )
        )
        http_result = await Agent(http_provider, ToolRegistry()).run(
            "Return the configured local protocol response."
        )
        failing_provider = OpenAICompatibleProvider(
            Settings(
                api_key="demo-only-token",
                model=settings.model,
                base_url=f"{base_url}/failure",
                request_timeout=settings.request_timeout,
            )
        )
        try:
            await failing_provider.complete(
                [
                    Message(
                        role="user",
                        content="Trigger the documented HTTP error.",
                    )
                ],
                [],
            )
        except ProviderError as exc:
            provider_http_error = str(exc)

    errors: dict[str, str] = {"provider_http_error": provider_http_error}
    try:
        OpenAICompatibleProvider(Settings())
    except ConfigurationError as exc:
        errors["missing_provider_key"] = str(exc)
    try:
        await Agent(
            ScriptedProvider(
                [
                    AssistantTurn(
                        tool_calls=(
                            ToolCall(
                                id="limit-call",
                                name="lookup_reference",
                                arguments={"reference": "DEMO-REF-001"},
                            ),
                        )
                    )
                ]
            ),
            registry,
            max_turns=1,
        ).run("Exercise the configured turn limit.")
    except StepLimitExceeded as exc:
        errors["turn_limit"] = str(exc)
    try:
        await registry.invoke(ToolCall("unknown-call", "not_registered", arguments={}))
    except ToolExecutionError as exc:
        errors["unknown_tool"] = str(exc)

    try:
        package_version = version("citruscare-sdk")
    except PackageNotFoundError as exc:
        raise RuntimeError(
            "Install the local citruscare-sdk package before running this demo."
        ) from exc

    return {
        "package": {"distribution": "citruscare-sdk", "version": package_version},
        "settings": {
            "source": "CITRUSCARE_* environment variables",
            "model": settings.model,
            "base_url": settings.base_url,
            "request_timeout_seconds": settings.request_timeout,
            "max_turns": settings.max_turns,
            "api_key_exposed": False,
        },
        "agent": {
            "provider": "CitrusCare ScriptedProvider (deterministic local provider)",
            "content": agent_result.content,
            "turns": agent_result.turns,
            "tool_result": json.loads(tool_message.content),
            "message_roles": [message.role for message in agent_result.messages],
            "registered_provider_tool_names": [
                item["function"]["name"] for item in registry.provider_schemas()
            ],
        },
        "direct_sync_tool_result": formatted_status,
        "http_adapter": {
            "transport": "real urllib HTTP request to a loopback protocol fixture",
            "ai_generated": False,
            "content": http_result.content,
        },
        "governance": {
            "consent_granted": grant.active,
            "consent_active_after_grant": consent_active_after_grant,
            "consent_active_after_revoke": consent.has_consent(
                "synthetic-subject-001", "demo-purpose"
            ),
            "revocation_recorded": revoked.revoked_at is not None,
            "audit_events": [
                {
                    "event_type": event.event_type,
                    "metadata": dict(event.metadata),
                }
                for event in audit.events
            ],
            "audit_contains_prompt": any(
                "Check synthetic reference" in repr(event) for event in audit.events
            ),
        },
        "clinical_observation": {
            "code": observation.code,
            "value": observation.value,
            "unit": observation.unit,
            "effective_at": observation.effective_at.isoformat(),
            "subject_reference": observation.subject_reference,
        },
        "handled_errors": errors,
    }


def run_demo() -> dict[str, Any]:
    """Run the consumer flow and return the same data that the CLI prints."""
    return asyncio.run(_run_demo_async())


def main() -> None:
    print(json.dumps(run_demo(), indent=2, sort_keys=True))
