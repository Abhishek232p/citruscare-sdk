from __future__ import annotations

import asyncio
import importlib.metadata
import unittest
from datetime import UTC, datetime

from citruscare_integration_demo import run_demo

from citruscare import (
    Agent,
    AgentResult,
    AssistantTurn,
    AuditError,
    AuditEvent,
    AuditSink,
    ConfigurationError,
    ConsentGrant,
    ConsentLedger,
    MemoryAuditSink,
    Message,
    OpenAICompatibleProvider,
    ProviderError,
    ScriptedProvider,
    Settings,
    StepLimitExceeded,
    Tool,
    ToolCall,
    ToolExecutionError,
    ToolRegistry,
)
from citruscare.clinical import ClinicalObservation


class ConsumerIntegrationTests(unittest.TestCase):
    def test_sdk_distribution_is_installed_for_consumer(self) -> None:
        self.assertEqual(
            importlib.metadata.version("citruscare-sdk"),
            "0.1.0",
        )

    def test_demo_exercises_installed_sdk_capabilities(self) -> None:
        output = run_demo()
        self.assertEqual(
            output["package"],
            {"distribution": "citruscare-sdk", "version": "0.1.0"},
        )
        self.assertEqual(
            output["agent"]["content"], "Reference DEMO-REF-001 is active."
        )
        self.assertEqual(output["agent"]["turns"], 2)
        self.assertEqual(
            output["agent"]["tool_result"],
            {"reference": "DEMO-REF-001", "status": "active"},
        )
        self.assertEqual(
            output["agent"]["message_roles"],
            ["system", "user", "assistant", "tool", "assistant"],
        )
        self.assertEqual(output["direct_sync_tool_result"], "Status: active")
        self.assertFalse(output["http_adapter"]["ai_generated"])
        self.assertIn("not generated by an AI model", output["http_adapter"]["content"])
        self.assertTrue(output["governance"]["consent_granted"])
        self.assertTrue(output["governance"]["consent_active_after_grant"])
        self.assertFalse(output["governance"]["consent_active_after_revoke"])
        self.assertTrue(output["governance"]["revocation_recorded"])
        self.assertFalse(output["governance"]["audit_contains_prompt"])
        self.assertEqual(
            output["clinical_observation"]["subject_reference"],
            "Patient/synthetic-subject-001",
        )
        self.assertEqual(
            set(output["handled_errors"]),
            {
                "missing_provider_key",
                "provider_http_error",
                "turn_limit",
                "unknown_tool",
            },
        )
        self.assertEqual(output["handled_errors"]["provider_http_error"],
                         "Provider returned HTTP 503")

    def test_public_api_can_be_used_from_consumer_application(self) -> None:
        self.assertTrue(issubclass(ConfigurationError, Exception))
        self.assertTrue(issubclass(ProviderError, Exception))
        self.assertTrue(issubclass(ToolExecutionError, Exception))
        self.assertTrue(issubclass(StepLimitExceeded, Exception))
        self.assertIsInstance(AuditEvent.create("consumer_test"), AuditEvent)
        self.assertTrue(callable(AuditSink.record))
        self.assertIsInstance(
            ConsentGrant("s", "p", datetime.now(UTC)), ConsentGrant
        )
        self.assertIsInstance(Message("user", "consumer request"), Message)
        self.assertIsInstance(
            AgentResult("done", 1, (Message("assistant", "done"),)), AgentResult
        )
        self.assertIsInstance(Settings(), Settings)
        self.assertIsInstance(ToolRegistry(), ToolRegistry)
        self.assertTrue(callable(Tool))
        self.assertTrue(callable(ToolCall))
        self.assertTrue(callable(ClinicalObservation))
        self.assertTrue(callable(Agent))
        self.assertTrue(callable(ScriptedProvider))
        self.assertTrue(callable(OpenAICompatibleProvider))
        self.assertTrue(callable(ConsentLedger))

    def test_consumer_can_run_scripted_agent_and_inspect_audit(self) -> None:
        audit = MemoryAuditSink()
        result = asyncio.run(
            Agent(
                ScriptedProvider(
                    [AssistantTurn(content="Consumer flow complete.")]
                ),
                ToolRegistry(),
                audit_sink=audit,
            ).run("synthetic test request")
        )
        self.assertEqual(result.content, "Consumer flow complete.")
        self.assertEqual(result.messages[1].content, "synthetic test request")
        self.assertEqual(
            [event.event_type for event in audit.events],
            ["run_started", "run_completed"],
        )

    def test_configured_provider_requires_credentials(self) -> None:
        with self.assertRaises(ConfigurationError):
            OpenAICompatibleProvider(Settings())

    def test_audit_sink_failures_are_not_silently_ignored(self) -> None:
        class BrokenAuditSink:
            def record(self, event: AuditEvent) -> None:
                del event
                raise OSError("local sink is unavailable")

        with self.assertRaisesRegex(AuditError, "Could not record audit event"):
            asyncio.run(
                Agent(
                    ScriptedProvider([AssistantTurn(content="not reached")]),
                    ToolRegistry(),
                    audit_sink=BrokenAuditSink(),
                ).run("synthetic request")
            )

    def test_installed_sdk_public_symbols_are_consumer_importable(self) -> None:
        self.assertIsInstance(Agent, type)
        self.assertIsInstance(Settings, type)
        self.assertIsInstance(Tool, type)
        self.assertIsInstance(ToolCall, type)
        self.assertIsInstance(ConsentLedger, type)
        self.assertIsInstance(ScriptedProvider, type)
        self.assertIsInstance(OpenAICompatibleProvider, type)
        self.assertIsInstance(ClinicalObservation, type)


if __name__ == "__main__":
    unittest.main()
